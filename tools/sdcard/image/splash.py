def draw(w, h, lines):
    px = bytearray(bytes(NAVY) * (w * h))
    def text(y, s, scale, col):
        tw = len(s) * 6 * scale - scale
        x0 = (w - tw) // 2
        for i, ch in enumerate(s.upper()):
            g = F.get(ch, F[' '])
            for r, row in enumerate(g):
                for c, b in enumerate(row):
                    if b != '#': continue
                    for yy in range(scale):
                        o = ((y + r * scale + yy) * w + x0 + (i * 6 + c) * scale) * 3
                        px[o:o + 3 * scale] = bytes(col) * scale
    def bar(y, hgt, col, x0, x1):
        for yy in range(y, y + hgt):
            o = (yy * w + x0) * 3
            px[o:o + (x1 - x0) * 3] = bytes(col) * (x1 - x0)
    for kind, *a in lines:
        if kind == 't': text(*a)
        else: bar(*a)
    return px


def png(path, w, h, px):
    raw = b''.join(b'\0' + bytes(px[y * w * 3:(y + 1) * w * 3]) for y in range(h))
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xFFFFFFFF)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)) +
                chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


