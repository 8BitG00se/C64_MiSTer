def glyph8(ch):
    """8 bytes of a normal character: the 5 x 7 glyph on an 8 x 8 cell, 1 px in from the left"""
    rows = G[ch]; out = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == '#': v |= 0x80 >> (i + 1)
        out.append(v)
    return out + [0]

def big(ch):
    """the glyph doubled (10 x 14) on a 16 x 16 area -> 4 cells of 8 bytes: [tl, tr, bl, br]"""
    rows = G[ch]
    bm = [[0] * 16 for _ in range(16)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                for dy in (0, 1):
                    for dx in (0, 1): bm[1 + y * 2 + dy][3 + x * 2 + dx] = 1
    cells = []
    for cy in (0, 1):
        for cx in (0, 1):
            cell = []
            for y in range(8):
                v = 0
                for x in range(8):
                    if bm[cy * 8 + y][cx * 8 + x]: v |= 0x80 >> x
                cell.append(v)
            cells.append(cell)
    return cells

def build():
    """-> (charset bytes 2048, small code map {char: code}, big map {char: (tl,tr,bl,br) codes}, SEG, SEGGAP)"""
    chars = [[0] * 8]
    small = {' ': 0}
    for ch in G:
        chars.append(glyph8(ch)); small[ch] = len(chars) - 1
    seg = len(chars)
    chars.append([0x00, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00])      # one health segment: 7 x 6 with a gap
    chars.append([0x00, 0x3C, 0x42, 0x42, 0x42, 0x42, 0x3C, 0x00])      # SEG + 1: a round-win marker, empty (ring)
    chars.append([0x00, 0x3C, 0x7E, 0x7E, 0x7E, 0x7E, 0x3C, 0x00])      # SEG + 2: a round-win marker, won (disc)
    bigm = {' ': (0, 0, 0, 0)}
    for ch in G:
        cells = big(ch); codes = []
        for c in cells:
            if c in chars: codes.append(chars.index(c))
            else: chars.append(c); codes.append(len(chars) - 1)
        bigm[ch] = tuple(codes)
    assert len(chars) <= 256, len(chars)
    cs = bytearray()
    for c in chars: cs += bytes(c)
    cs += bytes(2048 - len(cs))
    return bytes(cs), small, bigm, seg
